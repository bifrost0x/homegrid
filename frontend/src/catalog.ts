export const icons: Record<string, LucideIcon> = Object.fromEntries(
  Object.entries(catalog).map(([id, [Icon]]) => [id, Icon]),
);
export function findIcons(query: string) {
  const words = query.toLocaleLowerCase().trim().split(/\s+/).filter(Boolean);
  return Object.entries(icons).filter(([id]) =>
    words.every((word) => (id + " " + catalog[id][1]).includes(word)),
  );
}
export interface ServiceTemplate {
  name: string;
  description: string;
  icon: string;
  icon_color: IconColor;
  keywords: string;
  category: string;
}
function template(
  name: string,
  description: string,
  icon: string,
  icon_color: IconColor,
  keywords: string,
  category: string,
): ServiceTemplate {
  return {
    name,
    description,
    icon: "service:" + icon,
    icon_color,
    keywords,
    category,
  };
}
